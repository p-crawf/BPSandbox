DAYS = 358
chapters = [(b, c, slug, vids) for b, n, slug, vids in BOOKS for c in range(1, n + 1)]
total = len(chapters)

def video_for(vids, ch):
    return next(v for a, z, v in vids if a <= ch <= z)

def label(chs):
    parts, i = [], 0
    while i < len(chs):
        b = chs[i][0]; j = i
        while j + 1 < len(chs) and chs[j + 1][0] == b: j += 1
        a, z = chs[i][1], chs[j][1]
        parts.append(f"{b} {a}" if a == z else f"{b} {a}–{z}")
        i = j + 1
    return "; ".join(parts)

days = []
for d in range(DAYS):
    lo, hi = math.floor(d * total / DAYS), math.floor((d + 1) * total / DAYS)
    chs = chapters[lo:hi]
    b, c, slug, vids = chs[0]
    days.append({"reading": label(chs), "start": {"book": slug, "chapter": c}, "video": video_for(vids, c)})

out = pathlib.Path(__file__).resolve().parents[1] / "reading-plans-1" / "plan-schedule.js"
out.write_text("/* SAMPLE schedule generated by sandbox/tools/build-sample-plan.py.\n"
               "   Not the real One Story That Leads to Jesus plan: replace `days` with it. */\n"
               "window.BP_PLAN = " + json.dumps({"title": "One Story That Leads to Jesus", "sample": True,
               "startDate": "2026-01-01", "days": days}, ensure_ascii=False, indent=1) + ";\n")
print(len(days), "days;", total, "chapters ->", out)
