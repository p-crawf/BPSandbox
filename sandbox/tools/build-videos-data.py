#!/usr/bin/env python3
"""Build sandbox/assets/videos-data.js from the video links already in sandbox pages.

Run from the repo root:  python3 sandbox/tools/build-videos-data.py
"""
import html, json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SB = ROOT / "sandbox"
A_RE = re.compile(r'<a [^>]*href="https://bibleproject\.com/videos/([^"/]+)/"[^>]*>(.*?)</a>', re.S)

# Mux playback IDs for videos the sandbox can actually play (from /videos/* concept pages).
MUX = {}
for p in (ROOT / "videos").glob("*/index.html"):
    m = re.search(r'playback-id="([^"]+)"', p.read_text())
    if m:
        MUX[p.parent.name] = m.group(1)

def text(fragment):
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", fragment))).strip()

def cls(fragment, name):
    m = re.search(r'class="[^"]*\b' + re.escape(name) + r'\b[^"]*"[^>]*>(.*?)</(?:p|h3|div|span)>', fragment, re.S)
    return text(m.group(1)) if m else ""

def base_img(fragment):
    srcs = re.findall(r'<img[^>]*src="([^"]+)"', fragment)
    return re.sub(r"/tr:[^/]+/", "/", srcs[-1]) if srcs else ""

videos, series = {}, {}

def merge(slug, **kw):
    v = videos.setdefault(slug, {"slug": slug, "title": "", "description": "", "duration": "",
                                 "image": "", "series": []})
    for k, val in kw.items():
        if not val:
            continue
        if k == "image":
            # Prefer 16:9 artwork over square tiles.
            if not v["image"] or ("16" in val and "16" not in v["image"]) or "1-1" in v["image"] or "_1.1" in v["image"]:
                v["image"] = val
        elif not v.get(k) or (k == "description" and len(val) > len(v[k])):
            v[k] = val

def add_series(key, title, href, slug):
    s = series.setdefault(key, {"key": key, "title": title, "href": href, "videos": []})
    if slug not in s["videos"]:
        s["videos"].append(slug)
    if key not in videos[slug]["series"]:
        videos[slug]["series"].append(key)

# Collection pages: ordered series with descriptions.
for page in sorted((SB / "videos" / "collections").glob("*/index.html")):
    s = page.read_text()
    title = text(re.search(r'data-testid="video-collection-title">(.*?)</h1>', s, re.S).group(1))
    key = page.parent.name
    for slug, body in A_RE.findall(s):
        if slug in ("all", "collections"):
            continue
        merge(slug, title=cls(body, "video-block-title"), description=cls(body, "video-block-description"),
              duration=cls(body, "video-block-artwork-duration"), image=base_img(body))
        add_series(key, title, "../collections/" + key + "/", slug)

# Videos index carousels.
s = (SB / "videos" / "index.html").read_text()
for slug, body in A_RE.findall(s):
    if slug in ("all", "collections"):
        continue
    merge(slug, title=cls(body, "video-block-title"), duration=cls(body, "video-block-artwork-duration"),
          image=base_img(body))

# Spirit of God collection: "<Series> • N min" meta + title.
s = (SB / "collections" / "spirit-of-god" / "index.html").read_text()
for slug, body in A_RE.findall(s):
    parts = [p for p in (text(x) for x in re.split(r"<[^>]+>", body)) if p]
    meta = parts[0] if parts else ""
    label, _, mins = meta.partition("•")
    merge(slug, title=parts[1] if len(parts) > 1 else "", image=base_img(body),
          label=label.strip(), duration=mins.strip())

for slug, v in videos.items():
    if slug in MUX:
        v["playbackId"] = MUX[slug]
    if not v["title"]:
        v["title"] = slug.replace("-", " ").title()

out = SB / "assets" / "videos-data.js"
out.write_text("/* Generated by sandbox/tools/build-videos-data.py — do not edit by hand. */\n"
               "window.BP_VIDEOS = " + json.dumps({"videos": videos, "series": series}, ensure_ascii=False, indent=1) + ";\n")
print(len(videos), "videos,", len(series), "series,", sum("playbackId" in v for v in videos.values()), "playable ->", out)
